CREATE TABLE categoria (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100 CHAR) NOT NULL,
    ativo CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT uq_categoria_nome UNIQUE (nome),
    CONSTRAINT ck_categoria_ativo CHECK (ativo IN ('S', 'N'))
);

CREATE TABLE ocorrencia (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    protocolo VARCHAR2(32 CHAR) NOT NULL,
    categoria_id NUMBER NOT NULL,
    endereco VARCHAR2(200 CHAR) NOT NULL,
    bairro VARCHAR2(100 CHAR) NOT NULL,
    descricao VARCHAR2(1000 CHAR) NOT NULL,
    status VARCHAR2(20 CHAR) DEFAULT 'Aberta' NOT NULL,
    criado_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_ocorrencia_protocolo UNIQUE (protocolo),
    CONSTRAINT fk_ocorrencia_categoria FOREIGN KEY (categoria_id) REFERENCES categoria(id),
    CONSTRAINT ck_ocorrencia_status CHECK (status IN ('Aberta', 'Em análise', 'Em andamento', 'Resolvida'))
);

CREATE TABLE historico_status (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ocorrencia_id NUMBER NOT NULL,
    status_anterior VARCHAR2(20 CHAR),
    status_novo VARCHAR2(20 CHAR) NOT NULL,
    observacao VARCHAR2(500 CHAR) NOT NULL,
    registrado_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_historico_ocorrencia FOREIGN KEY (ocorrencia_id) REFERENCES ocorrencia(id)
);

CREATE INDEX idx_ocorrencia_status ON ocorrencia(status);
CREATE INDEX idx_ocorrencia_categoria ON ocorrencia(categoria_id);
CREATE INDEX idx_historico_ocorrencia ON historico_status(ocorrencia_id);

CREATE SEQUENCE seq_protocolo START WITH 1 INCREMENT BY 1 NOCACHE;

